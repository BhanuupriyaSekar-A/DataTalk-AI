-- ---------------------------------------------------------------------
-- 1. Extend app.chat_history to store the full AI conversation record
-- ---------------------------------------------------------------------
ALTER TABLE app.chat_history ADD COLUMN IF NOT EXISTS conversation_id VARCHAR(64);
ALTER TABLE app.chat_history ADD COLUMN IF NOT EXISTS ai_interpretation TEXT;
ALTER TABLE app.chat_history ADD COLUMN IF NOT EXISTS report_title VARCHAR(255);
ALTER TABLE app.chat_history ADD COLUMN IF NOT EXISTS explanation TEXT;
ALTER TABLE app.chat_history ADD COLUMN IF NOT EXISTS chart_type VARCHAR(20);
ALTER TABLE app.chat_history ADD COLUMN IF NOT EXISTS row_count INTEGER;
ALTER TABLE app.chat_history ADD COLUMN IF NOT EXISTS error_message TEXT;
ALTER TABLE app.chat_history ADD COLUMN IF NOT EXISTS ai_provider VARCHAR(30);
ALTER TABLE app.chat_history ADD COLUMN IF NOT EXISTS source VARCHAR(30) DEFAULT 'AI';
ALTER TABLE app.chat_history ADD COLUMN IF NOT EXISTS duration_ms INTEGER;

COMMENT ON COLUMN app.chat_history.conversation_id IS 'Groups related questions of one chat conversation (generated by the application)';
COMMENT ON COLUMN app.chat_history.ai_interpretation IS 'How the AI understood the question (plain text)';
COMMENT ON COLUMN app.chat_history.report_title IS 'Report title proposed by the AI or predefined report name';
COMMENT ON COLUMN app.chat_history.explanation IS 'Short explanation of the report shown to the user';
COMMENT ON COLUMN app.chat_history.chart_type IS 'Suggested chart: table, bar, line or pie';
COMMENT ON COLUMN app.chat_history.row_count IS 'Total rows returned by the validated query';
COMMENT ON COLUMN app.chat_history.error_message IS 'Validation/AI/execution error shown to the user (no secrets)';
COMMENT ON COLUMN app.chat_history.ai_provider IS 'AI provider used (openai, gemini) or CACHE/PREDEFINED';
COMMENT ON COLUMN app.chat_history.source IS 'AI = generated by AI, CACHE = reused SQL, PREDEFINED = predefined report';
COMMENT ON COLUMN app.chat_history.duration_ms IS 'End-to-end processing time in milliseconds';
COMMENT ON COLUMN app.chat_history.query_status IS 'SUCCESS, REJECTED, AI_ERROR, EXECUTION_ERROR or NOT_ANSWERABLE';

CREATE INDEX IF NOT EXISTS idx_chat_history_conversation ON app.chat_history(conversation_id);
CREATE INDEX IF NOT EXISTS idx_chat_history_user_created ON app.chat_history(user_id, created_at DESC);

-- ---------------------------------------------------------------------
-- 2. Compact per-user AI context (preferences + conversation summary)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS app.user_ai_context (
    user_id     INTEGER PRIMARY KEY REFERENCES app_user.app_user(user_id) ON DELETE CASCADE,
    context     JSONB NOT NULL DEFAULT '{}'::jsonb,
    updated_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE app.user_ai_context IS 'Compact AI context per user: preferences and short conversation summary. Never stores passwords, API keys or payment card data.';
COMMENT ON COLUMN app.user_ai_context.user_id IS 'Owner of the context (one row per user)';
COMMENT ON COLUMN app.user_ai_context.context IS 'JSONB: {conversationId, preferences{}, recentTurns[{question,title,sql}], topics[]}';
COMMENT ON COLUMN app.user_ai_context.updated_at IS 'Last time the context was updated';

-- ---------------------------------------------------------------------
-- 3. Application role (user_datatalk) privileges on the app schema
-- ---------------------------------------------------------------------
GRANT USAGE ON SCHEMA app TO user_datatalk;
GRANT SELECT, INSERT, UPDATE, DELETE ON app.chat_history, app.user_ai_context TO user_datatalk;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA app TO user_datatalk;

-- ---------------------------------------------------------------------
-- 4. Read-only reporting role (datatalk_ro)
--    The application switches to this role (SET LOCAL ROLE) inside a
--    READ ONLY transaction for every AI/report query.
-- ---------------------------------------------------------------------
-- SELECT only on approved business schemas (re-applied for safety)
GRANT USAGE ON SCHEMA corp, location, device, txn TO datatalk_ro;
GRANT SELECT ON ALL TABLES IN SCHEMA corp, location, device, txn TO datatalk_ro;

-- No access to app / app_user schemas (users, passwords, chat history)
REVOKE ALL ON SCHEMA app FROM datatalk_ro;
REVOKE ALL ON ALL TABLES IN SCHEMA app FROM datatalk_ro;
REVOKE ALL ON SCHEMA app_user FROM datatalk_ro;
REVOKE ALL ON ALL TABLES IN SCHEMA app_user FROM datatalk_ro;

-- Read-only + 30 second timeout when datatalk_ro logs in directly
ALTER ROLE datatalk_ro SET default_transaction_read_only = on;
ALTER ROLE datatalk_ro SET statement_timeout = '30s';

-- Allow the application role to SET ROLE datatalk_ro without inheriting its
-- privileges (PostgreSQL 16+ syntax; Neon runs PostgreSQL 16-18).
GRANT datatalk_ro TO user_datatalk WITH INHERIT FALSE, SET TRUE;

-- ---------------------------------------------------------------------
-- 5. Verification
-- ---------------------------------------------------------------------
SELECT pg_has_role('user_datatalk', 'datatalk_ro', 'SET') AS app_can_set_ro_role;
SELECT has_schema_privilege('datatalk_ro', 'app', 'USAGE') AS ro_has_app_schema;   -- expected false
SELECT column_name FROM information_schema.columns
 WHERE table_schema = 'app' AND table_name = 'chat_history' ORDER BY ordinal_position;
SELECT to_regclass('app.user_ai_context') AS user_ai_context_table;
