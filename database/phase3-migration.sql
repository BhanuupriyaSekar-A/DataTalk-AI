CREATE TABLE IF NOT EXISTS app.export_job (
    job_id          VARCHAR(36)  PRIMARY KEY,
    user_id         INTEGER      NOT NULL REFERENCES app_user.app_user(user_id) ON DELETE CASCADE,
    chat_id         INTEGER      REFERENCES app.chat_history(chat_id) ON DELETE SET NULL,
    report_name     VARCHAR(255) NOT NULL,
    export_format   VARCHAR(10)  NOT NULL CHECK (export_format IN ('PDF', 'EXCEL')),
    job_status      VARCHAR(20)  NOT NULL CHECK (job_status IN ('RUNNING', 'COMPLETED', 'FAILED', 'EXPIRED')),
    delivery        VARCHAR(20)  NOT NULL DEFAULT 'BACKGROUND' CHECK (delivery IN ('DIRECT', 'BACKGROUND')),
    row_count       INTEGER,
    created_date    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_date  TIMESTAMP,
    file_location   VARCHAR(500),
    error_message   TEXT
);

COMMENT ON TABLE app.export_job IS 'PDF/Excel export requests per user (direct downloads and background jobs)';
COMMENT ON COLUMN app.export_job.job_id IS 'Export job ID (UUID generated by the application)';
COMMENT ON COLUMN app.export_job.user_id IS 'User who requested the export (only this user can download it)';
COMMENT ON COLUMN app.export_job.chat_id IS 'Chat history item (report) that was exported';
COMMENT ON COLUMN app.export_job.report_name IS 'Report title at export time';
COMMENT ON COLUMN app.export_job.export_format IS 'PDF or EXCEL';
COMMENT ON COLUMN app.export_job.job_status IS 'RUNNING, COMPLETED, FAILED or EXPIRED (file removed after retention period)';
COMMENT ON COLUMN app.export_job.delivery IS 'DIRECT = streamed to the browser, BACKGROUND = file generated by a background job';
COMMENT ON COLUMN app.export_job.row_count IS 'Number of rows written to the file';
COMMENT ON COLUMN app.export_job.created_date IS 'When the export was requested';
COMMENT ON COLUMN app.export_job.completed_date IS 'When the export finished (or failed)';
COMMENT ON COLUMN app.export_job.file_location IS 'Server file path of a background export (NULL for direct downloads)';
COMMENT ON COLUMN app.export_job.error_message IS 'Failure reason, if the export failed';

CREATE INDEX IF NOT EXISTS idx_export_job_user_created ON app.export_job(user_id, created_date DESC);

GRANT SELECT, INSERT, UPDATE ON app.export_job TO user_datatalk;
-- datatalk_ro keeps NO access to the app schema
REVOKE ALL ON app.export_job FROM datatalk_ro;

SELECT to_regclass('app.export_job') AS export_job_table;
